typedef unsigned int  u16;
typedef unsigned long u32;   /* long минимум 32 бита по стандарту C */

/* ---- —осто€ние √ѕ—„ ---- */
static u32 g_seed = 2463534242UL;

/* ------------------------------------------------------------
 *  »нициализаци€. ¬ызывать один раз перед использованием.
 *  Ќоль недопустим дл€ xorshift Ч подмен€ем на константу.
 * ------------------------------------------------------------ */
void random_init(u32 seed)
{
    if (seed == 0UL) {
        seed = 2463534242UL;
    }
    g_seed = seed;
}

/* ------------------------------------------------------------
 *  —ледующее 32-битное псевдослучайное число (xorshift32).
 * ------------------------------------------------------------ */
static u32 random_u32(void)
{
    u32 x = g_seed;
    x ^= x << 13;
    x ^= x >> 17;
    x ^= x << 5;
    g_seed = x;
    return x;
}

/* ------------------------------------------------------------
 *  —лучайное число в диапазоне [n1, n2] включительно.
 *  n1 > n2 Ч значени€ мен€ютс€ местами.
 *  n1 == n2 Ч возвращаетс€ это же число.
 * ------------------------------------------------------------ */
u16 random_range(u16 n1, u16 n2)
{
    u16 lo, hi;
    u32 range;

    if (n1 > n2) {
        lo = n2;
        hi = n1;
    } else {
        lo = n1;
        hi = n2;
    }

    /* range считаетс€ в u32 Ч иначе при lo=0, hi=65535
     * получим 0 из-за переполнени€ 16-битного типа. */
    range = (u32)hi - (u32)lo + 1UL;

    if (range == 0UL) {
        /* Ќедостижимо в u32, оставлено дл€ нагл€дности. */
        return (u16)random_u32();
    }

    return (u16)((u32)lo + random_u32() % range);
}
